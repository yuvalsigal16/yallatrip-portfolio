/**
 * The in-app guide, screen by screen. `target` is a [data-tour] mark on the real button;
 * no target = a card in the middle of the screen. A step whose button isn't on screen
 * (for example on a phone, or a trip that isn't shared) is skipped.
 * RULE: every new button gets a step in the guide of its screen (or a line in the step of the
 * button that opens it), in the same change that adds the button.
 * Travellers get each short guide by itself, once per account, the first time they reach that screen:
 * NEW (new trip form), START (the trip map), PLACE (the first place card they open) and DAYS (the first
 * visit to "לפי ימים"). TRIP, SAVED and HOME are the manager's fuller reference ("הדרכה").
 */
import { FEATURES, type FeatureKey } from '@/lib/features';

/** Text that names a feature only while it is switched on. */
const on = (k: FeatureKey, text: string) => (FEATURES[k] ? text : '');

/**
 * `open` = the button sits inside a list that is closed by default; the guide opens it for this step.
 * `expand` = the target is a folded row (<details>); the guide unfolds it for this step and folds it back.
 * A button inside a folded row is unfolded by itself. `a|b` = whichever of the two marks is on screen.
 */
/** `feature` = the step belongs to a feature that can be switched off (src/lib/features.ts); while off, the step is left out. */
export type TourStep = { target?: string; title: string; text: string; open?: 'trip-menu'; expand?: true; feature?: FeatureKey };
export type TourKind = 'home' | 'new' | 'start' | 'trip' | 'days' | 'saved' | 'place' | 'creator';

